// 예제 1: 트랜잭션 사용 패턴
func TransferMoney(db *sql.DB, fromUserID, toUserID int64, amount float64) error {
	ctx := context.Background()

	// 트랜잭션 시작
	tx, err := db.BeginTx(ctx, &sql.TxOptions{
		Isolation: sql.LevelRepeatableRead, // 적절한 격리 수준 선택
	})
	if err != nil {
		return fmt.Errorf("begin transaction: %w", err)
	}

	// defer로 롤백 보장 (커밋되면 롤백은 no-op)
	defer tx.Rollback()

	// 1. 출금 계좌에서 차감
	result, err := tx.ExecContext(ctx, `
		UPDATE accounts
		SET balance = balance - $1
		WHERE user_id = $2 AND balance >= $1
	`, amount, fromUserID)
	if err != nil {
		return fmt.Errorf("debit account: %w", err)
	}

	rowsAffected, _ := result.RowsAffected()
	if rowsAffected == 0 {
		return errors.New("insufficient balance or account not found")
	}

	// 2. 입금 계좌에 추가
	_, err = tx.ExecContext(ctx, `
		UPDATE accounts
		SET balance = balance + $1
		WHERE user_id = $2
	`, amount, toUserID)
	if err != nil {
		return fmt.Errorf("credit account: %w", err)
	}

	// 3. 거래 기록 저장
	_, err = tx.ExecContext(ctx, `
		INSERT INTO transactions (from_user_id, to_user_id, amount, created_at)
		VALUES ($1, $2, $3, NOW())
	`, fromUserID, toUserID, amount)
	if err != nil {
		return fmt.Errorf("record transaction: %w", err)
	}

	// 커밋
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit transaction: %w", err)
	}

	return nil
}

// 예제 2: N+1 쿼리 해결 - 배치 로딩
func GetUsersWithOrders(db *sql.DB, userIDs []int64) (map[int64][]Order, error) {
	if len(userIDs) == 0 {
		return nil, nil
	}

	// 단일 쿼리로 모든 주문 조회
	query := `
		SELECT id, user_id, status, amount, created_at
		FROM orders
		WHERE user_id = ANY($1)
		ORDER BY user_id, created_at DESC
	`

	rows, err := db.Query(query, userIDs)
	if err != nil {
		return nil, fmt.Errorf("query orders: %w", err)
	}
	defer rows.Close()

	// 결과를 user_id별로 그룹화
	result := make(map[int64][]Order)
	for rows.Next() {
		var order Order
		if err := rows.Scan(&order.ID, &order.UserID, &order.Status, &order.Amount, &order.CreatedAt); err != nil {
			return nil, fmt.Errorf("scan order: %w", err)
		}
		result[order.UserID] = append(result[order.UserID], order)
	}

	return result, nil
}

// 예제 3: Cursor 기반 페이지네이션
type OrderCursor struct {
	CreatedAt time.Time
	ID        int64
}

func GetOrdersWithCursor(db *sql.DB, userID int64, cursor *OrderCursor, limit int) ([]Order, *OrderCursor, error) {
	var query string
	var args []interface{}

	if cursor == nil {
		// 첫 페이지
		query = `
			SELECT id, user_id, status, amount, created_at
			FROM orders
			WHERE user_id = $1
			ORDER BY created_at DESC, id DESC
			LIMIT $2
		`
		args = []interface{}{userID, limit + 1} // limit+1로 다음 페이지 존재 여부 확인
	} else {
		// 다음 페이지 (커서 이후)
		query = `
			SELECT id, user_id, status, amount, created_at
			FROM orders
			WHERE user_id = $1 AND (created_at, id) < ($2, $3)
			ORDER BY created_at DESC, id DESC
			LIMIT $4
		`
		args = []interface{}{userID, cursor.CreatedAt, cursor.ID, limit + 1}
	}

	rows, err := db.Query(query, args...)
	if err != nil {
		return nil, nil, fmt.Errorf("query orders: %w", err)
	}
	defer rows.Close()

	var orders []Order
	for rows.Next() {
		var order Order
		if err := rows.Scan(&order.ID, &order.UserID, &order.Status, &order.Amount, &order.CreatedAt); err != nil {
			return nil, nil, fmt.Errorf("scan order: %w", err)
		}
		orders = append(orders, order)
	}

	// 다음 페이지 커서 생성
	var nextCursor *OrderCursor
	if len(orders) > limit {
		orders = orders[:limit] // 실제 반환은 limit개만
		lastOrder := orders[len(orders)-1]
		nextCursor = &OrderCursor{
			CreatedAt: lastOrder.CreatedAt,
			ID:        lastOrder.ID,
		}
	}

	return orders, nextCursor, nil
}

// 예제 4: 락을 사용한 동시성 제어 (재고 차감)
func DeductInventory(db *sql.DB, productID int64, quantity int) error {
	ctx := context.Background()

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()

	// FOR UPDATE로 행 수준 락 획득
	var currentStock int
	err = tx.QueryRowContext(ctx, `
		SELECT stock FROM products WHERE id = $1 FOR UPDATE
	`, productID).Scan(&currentStock)
	if err != nil {
		return fmt.Errorf("select for update: %w", err)
	}

	if currentStock < quantity {
		return errors.New("insufficient stock")
	}

	// 재고 차감
	_, err = tx.ExecContext(ctx, `
		UPDATE products SET stock = stock - $1 WHERE id = $2
	`, quantity, productID)
	if err != nil {
		return fmt.Errorf("update stock: %w", err)
	}

	return tx.Commit()
}

// 예제 5: 배치 INSERT
func BatchInsertOrders(db *sql.DB, orders []Order) error {
	if len(orders) == 0 {
		return nil
	}

	// PostgreSQL의 경우 COPY 명령이 더 빠르지만,
	// 여기서는 일반적인 배치 INSERT 예시
	ctx := context.Background()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()

	stmt, err := tx.PrepareContext(ctx, `
		INSERT INTO orders (user_id, status, amount, created_at)
		VALUES ($1, $2, $3, $4)
	`)
	if err != nil {
		return fmt.Errorf("prepare statement: %w", err)
	}
	defer stmt.Close()

	for _, order := range orders {
		_, err := stmt.ExecContext(ctx, order.UserID, order.Status, order.Amount, order.CreatedAt)
		if err != nil {
			return fmt.Errorf("insert order: %w", err)
		}
	}

	return tx.Commit()
}

