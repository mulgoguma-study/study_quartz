// 5. 트랜잭션의 장점과 단점
// ============================================================================

/*
【 트랜잭션이란? 】

여러 SQL 문을 하나의 논리적 작업 단위로 묶는 것
모두 성공하거나 모두 실패 (All or Nothing)


【 ACID 속성 】

┌─────────────────────────────────────────────────────────────────────────────┐
│  A - Atomicity (원자성)                                                     │
│  ─────────────────────                                                      │
│  트랜잭션의 모든 연산이 완전히 수행되거나 전혀 수행되지 않음                 │
│                                                                             │
│  예: 계좌 이체                                                              │
│  1. A 계좌에서 100원 출금                                                   │
│  2. B 계좌에 100원 입금                                                     │
│  → 둘 다 성공하거나, 둘 다 실패                                             │
├─────────────────────────────────────────────────────────────────────────────┤
│  C - Consistency (일관성)                                                   │
│  ───────────────────────                                                    │
│  트랜잭션 전후로 데이터베이스가 일관된 상태 유지                             │
│                                                                             │
│  예: 잔액은 음수가 될 수 없음                                               │
│  → 이체 후에도 이 규칙이 유지되어야 함                                      │
├─────────────────────────────────────────────────────────────────────────────┤
│  I - Isolation (격리성)                                                     │
│  ──────────────────────                                                     │
│  동시에 실행되는 트랜잭션들이 서로 영향을 주지 않음                          │
│                                                                             │
│  예: A가 이체 중일 때, B가 잔액 조회해도 중간 상태 안 보임                   │
├─────────────────────────────────────────────────────────────────────────────┤
│  D - Durability (지속성)                                                    │
│  ───────────────────────                                                    │
│  커밋된 트랜잭션의 결과는 영구적으로 보존                                    │
│                                                                             │
│  예: 이체 완료 후 서버 다운되어도 이체 내역 유지                             │
└─────────────────────────────────────────────────────────────────────────────┘


【 트랜잭션의 장점 】

1. 데이터 무결성 보장
────────────────────
   - 중간에 실패해도 이전 상태로 롤백
   - 데이터 불일치 방지

2. 동시성 제어
─────────────
   - 여러 사용자가 동시 접근해도 안전
   - 격리 수준에 따른 동시성 조절 가능

3. 복구 용이성
─────────────
   - 장애 발생 시 트랜잭션 로그로 복구
   - 커밋된 것만 반영, 미커밋은 롤백

4. 비즈니스 로직 단순화
─────────────────────
   - 복잡한 에러 처리 코드 감소
   - "실패하면 롤백"이라는 단순한 모델


【 트랜잭션의 단점 】

1. 성능 오버헤드
───────────────
   ┌─────────────────────────────────────────────────────────────────┐
   │  트랜잭션 없이:                                                 │
   │  INSERT → 완료 (빠름)                                           │
   │                                                                 │
   │  트랜잭션 있으면:                                               │
   │  BEGIN → 로그 기록 → INSERT → 로그 기록 → COMMIT → fsync        │
   │          ────────            ────────            ─────          │
   │          Undo log            Redo log            디스크 동기화   │
   │                                                                 │
   │  ★ WAL(Write-Ahead Logging) 오버헤드                            │
   │  ★ 락 획득/해제 오버헤드                                        │
   │  ★ 디스크 동기화(fsync) 오버헤드                                │
   └─────────────────────────────────────────────────────────────────┘

2. 락 경합과 데드락
─────────────────
   -- 트랜잭션 A
   BEGIN;
   UPDATE accounts SET balance = balance - 100 WHERE id = 1;  -- 락 획득
   UPDATE accounts SET balance = balance + 100 WHERE id = 2;  -- 대기
   COMMIT;

   -- 트랜잭션 B (동시 실행)
   BEGIN;
   UPDATE accounts SET balance = balance - 50 WHERE id = 2;   -- 락 획득
   UPDATE accounts SET balance = balance + 50 WHERE id = 1;   -- 대기
   COMMIT;

   → 데드락 발생! DB가 하나를 강제 롤백

3. 긴 트랜잭션의 문제
──────────────────
   - 락 보유 시간 증가 → 다른 트랜잭션 대기
   - Undo 로그 증가 → 디스크 사용량 증가
   - 롤백 시 오래 걸림

4. 격리 수준에 따른 트레이드오프
────────────────────────────────
   ┌───────────────────┬──────────────┬──────────────┬───────────────┐
   │    격리 수준      │    동시성    │   일관성     │   성능        │
   ├───────────────────┼──────────────┼──────────────┼───────────────┤
   │ READ UNCOMMITTED  │    높음      │   낮음       │   높음        │
   │ READ COMMITTED    │    중간      │   중간       │   중간        │
   │ REPEATABLE READ   │    낮음      │   높음       │   낮음        │
   │ SERIALIZABLE      │   매우 낮음  │  매우 높음   │   매우 낮음   │
   └───────────────────┴──────────────┴──────────────┴───────────────┘


【 트랜잭션 Best Practices 】

1. 트랜잭션은 짧게 유지
─────────────────────
   // 나쁜 예
   tx.Begin()
   data := fetchFromExternalAPI()  // 외부 API 호출 (느림)
   tx.Insert(data)
   tx.Commit()

   // 좋은 예
   data := fetchFromExternalAPI()  // 트랜잭션 밖에서 처리
   tx.Begin()
   tx.Insert(data)
   tx.Commit()

2. 적절한 격리 수준 선택
──────────────────────
   - 금융 거래: SERIALIZABLE 또는 REPEATABLE READ
   - 일반 조회: READ COMMITTED
   - 통계성 쿼리: READ UNCOMMITTED (dirty read 허용)

3. 일관된 락 순서 유지 (데드락 방지)
───────────────────────────────────
   // 항상 id가 작은 것부터 락
   ids := []int{id1, id2}
   sort.Ints(ids)
   for _, id := range ids {
       tx.LockRow(id)
   }

4. 필요한 경우만 트랜잭션 사용
────────────────────────────
   - 단일 INSERT/UPDATE는 트랜잭션 불필요 (자체가 원자적)
   - 여러 테이블/행 수정 시에만 명시적 트랜잭션

5. 타임아웃 설정
───────────────
   SET lock_timeout = '5s';  -- 5초 이상 락 대기하면 실패
   SET statement_timeout = '30s';  -- 30초 이상 쿼리 실행하면 실패
*/

