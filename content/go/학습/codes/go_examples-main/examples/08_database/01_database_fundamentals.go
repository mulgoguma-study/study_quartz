// 예제 7: 슬로우 쿼리 감지를 위한 래퍼
type QueryLogger struct {
	db        *sql.DB
	threshold time.Duration
}

func (ql *QueryLogger) Query(ctx context.Context, query string, args ...interface{}) (*sql.Rows, error) {
	start := time.Now()
	rows, err := ql.db.QueryContext(ctx, query, args...)
	duration := time.Since(start)

	if duration > ql.threshold {
		log.Printf("SLOW QUERY (%v): %s", duration, query)
	}

	return rows, err
}

