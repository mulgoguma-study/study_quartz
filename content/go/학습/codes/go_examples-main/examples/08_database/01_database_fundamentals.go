// 4. 인덱스가 많을 때 INSERT/UPDATE 성능 저하 해결법
// ============================================================================

/*
【 왜 느려지는가? 】

INSERT 시 발생하는 일:
────────────────────
1. 테이블에 데이터 삽입
2. 인덱스 1 업데이트 (B+Tree 탐색 → 삽입 → 필요시 페이지 분할)
3. 인덱스 2 업데이트 (B+Tree 탐색 → 삽입 → 필요시 페이지 분할)
4. 인덱스 3 업데이트 ...
5. 인덱스 N 업데이트 ...

┌─────────────────────────────────────────────────────────────────────────────┐
│                          인덱스 쓰기 오버헤드                                │
├─────────────────────────────────────────────────────────────────────────────┤
│                                                                             │
│   테이블 INSERT:  ████  (기본 비용)                                         │
│                                                                             │
│   + 인덱스 1:     ████  (추가 비용)                                         │
│   + 인덱스 2:     ████  (추가 비용)                                         │
│   + 인덱스 3:     ████  (추가 비용)                                         │
│   ────────────────────────────────                                          │
│   총 비용:        ████████████████                                          │
│                                                                             │
│   ★ 인덱스가 N개면, INSERT 비용이 대략 (N+1)배                              │
│   ★ 복합 인덱스는 단일 인덱스보다 업데이트 비용이 더 높음                    │
│   ★ 페이지 분할 발생 시 추가 I/O 오버헤드                                   │
│                                                                             │
└─────────────────────────────────────────────────────────────────────────────┘


【 해결 방법 】

1. 불필요한 인덱스 제거
─────────────────────
   -- 인덱스 사용 현황 확인 (PostgreSQL)
   SELECT schemaname, relname, indexrelname, idx_scan, idx_tup_read
   FROM pg_stat_user_indexes
   WHERE idx_scan = 0;  -- 한 번도 사용되지 않은 인덱스

   -- 인덱스 사용 현황 확인 (MariaDB/MySQL)
   SELECT * FROM sys.schema_unused_indexes;

   -- 또는
   SELECT
       table_schema, table_name, index_name,
       stat_value as rows_selected
   FROM mysql.innodb_index_stats
   WHERE stat_name = 'n_diff_pfx01';

2. 중복 인덱스 통합
──────────────────
   -- 이런 경우 중복됨
   INDEX idx_a (a)
   INDEX idx_ab (a, b)  -- idx_a는 불필요 (idx_ab가 a만 있는 쿼리도 커버)

   -- 통합 후
   INDEX idx_ab (a, b)  -- 하나로 충분

3. 배치 INSERT 활용
──────────────────
   -- 나쁜 예 (각각 인덱스 업데이트)
   INSERT INTO orders VALUES (1, ...);
   INSERT INTO orders VALUES (2, ...);
   INSERT INTO orders VALUES (3, ...);

   -- 좋은 예 (한 번에 인덱스 업데이트, 트랜잭션 최적화)
   INSERT INTO orders VALUES
     (1, ...),
     (2, ...),
     (3, ...);

4. 대량 데이터 로드 시 인덱스 비활성화
───────────────────────────────────────
   -- 1. 인덱스 비활성화 (MariaDB/MySQL)
   ALTER TABLE orders DISABLE KEYS;

   -- 2. 데이터 대량 삽입
   LOAD DATA INFILE '/path/to/data.csv' INTO TABLE orders;

   -- 3. 인덱스 재활성화 (한 번에 재구축)
   ALTER TABLE orders ENABLE KEYS;

   -- PostgreSQL의 경우
   -- 1. 인덱스 삭제
   DROP INDEX idx_orders_user;

   -- 2. 데이터 삽입
   COPY orders FROM '/path/to/data.csv';

   -- 3. 인덱스 재생성 (CONCURRENTLY로 락 최소화)
   CREATE INDEX CONCURRENTLY idx_orders_user ON orders(user_id);

5. 파티셔닝 활용
───────────────
   -- 시간 기반 파티셔닝 (PostgreSQL)
   CREATE TABLE orders (
       id BIGINT,
       user_id INT,
       created_at TIMESTAMP,
       ...
   ) PARTITION BY RANGE (created_at);

   CREATE TABLE orders_2024_01 PARTITION OF orders
       FOR VALUES FROM ('2024-01-01') TO ('2024-02-01');

   -- 오래된 파티션은 인덱스 없이 운영 가능
   -- 각 파티션의 인덱스가 더 작아서 업데이트 빠름

6. 읽기/쓰기 분리 (Read Replica)
────────────────────────────────
   ┌─────────────┐     Write     ┌─────────────┐
   │   Client    │──────────────▶│   Primary   │
   │             │               │   (쓰기용)   │
   │             │               │ 인덱스 최소화│
   │             │               └──────┬──────┘
   │             │                      │ 복제
   │             │     Read       ┌─────▼──────┐
   │             │◀──────────────│   Replica   │
   └─────────────┘               │  (읽기용)   │
                                 │ 인덱스 풍부  │
                                 └─────────────┘

7. Partial Index (조건부 인덱스)
───────────────────────────────
   -- 전체 데이터가 아닌 일부에만 인덱스 생성 (PostgreSQL)
   CREATE INDEX idx_active_orders ON orders(user_id, created_at)
   WHERE status = 'active';  -- active 주문만 인덱싱

   -- 장점:
   -- 1. 인덱스 크기 감소
   -- 2. INSERT 시 조건 불만족하면 인덱스 업데이트 안 함
   -- 3. 자주 조회되는 데이터만 인덱싱

8. 인덱스 Fill Factor 조정
─────────────────────────
   -- 페이지에 여유 공간을 남겨 페이지 분할 감소 (PostgreSQL)
   CREATE INDEX idx_orders_user ON orders(user_id) WITH (fillfactor = 70);

   -- 30% 여유 공간 → INSERT 시 페이지 분할 빈도 감소
   -- 단점: 인덱스 크기 증가
*/

