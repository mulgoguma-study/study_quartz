/*
【 복합 인덱스란? 】

여러 컬럼을 하나의 인덱스로 묶어서 생성하는 것

예시:
CREATE INDEX idx_user_status_created ON orders(user_id, status, created_at);

┌─────────────────────────────────────────────────────────────────────────────┐
│                          복합 인덱스 구조 (B+Tree)                          │
├─────────────────────────────────────────────────────────────────────────────┤
│                                                                             │
│     인덱스 키: (user_id, status, created_at) 순서로 정렬                    │
│                                                                             │
│     ┌─────────────────────────────────────────────────────────────────┐     │
│     │ (1, 'pending', 2024-01-01) → Row 포인터                         │     │
│     │ (1, 'pending', 2024-01-02) → Row 포인터                         │     │
│     │ (1, 'completed', 2024-01-01) → Row 포인터                       │     │
│     │ (2, 'pending', 2024-01-01) → Row 포인터                         │     │
│     │ (2, 'pending', 2024-01-03) → Row 포인터                         │     │
│     │ ...                                                             │     │
│     └─────────────────────────────────────────────────────────────────┘     │
│                                                                             │
│     ★ 첫 번째 컬럼(user_id) 기준으로 먼저 정렬                              │
│     ★ 같은 user_id 내에서 두 번째 컬럼(status)으로 정렬                     │
│     ★ 같은 (user_id, status) 내에서 세 번째 컬럼(created_at)으로 정렬       │
│                                                                             │
└─────────────────────────────────────────────────────────────────────────────┘

【 복합 인덱스의 장점 】

1. 커버링 인덱스 (Covering Index)
───────────────────────────────
   - 인덱스만으로 쿼리 응답 가능 (테이블 접근 불필요)
   - I/O 감소로 성능 대폭 향상

   -- 인덱스: (user_id, status, created_at)
   -- 이 쿼리는 테이블을 읽지 않음 (Index Only Scan)
   SELECT user_id, status, created_at
   FROM orders
   WHERE user_id = 1 AND status = 'pending';

2. 다중 조건 쿼리 최적화
────────────────────────
   -- 하나의 인덱스로 여러 조건 처리
   SELECT * FROM orders
   WHERE user_id = 1
     AND status = 'pending'
     AND created_at > '2024-01-01';

3. 정렬 최적화
─────────────
   -- ORDER BY도 인덱스 활용 (별도 정렬 불필요)
   SELECT * FROM orders
   WHERE user_id = 1
   ORDER BY status, created_at;

4. 공간 효율성
─────────────
   - 개별 인덱스 3개보다 복합 인덱스 1개가 공간 절약
   - 인덱스 관리 오버헤드 감소


【 복합 인덱스의 문제점과 주의사항 】

1. 컬럼 순서가 매우 중요 (Leftmost Prefix Rule)
─────────────────────────────────────────────────

   인덱스: (user_id, status, created_at)

   ✅ 인덱스 사용 가능:
   - WHERE user_id = 1
   - WHERE user_id = 1 AND status = 'pending'
   - WHERE user_id = 1 AND status = 'pending' AND created_at > '2024-01-01'

   ❌ 인덱스 사용 불가 (또는 비효율적):
   - WHERE status = 'pending'                    -- user_id 없음
   - WHERE created_at > '2024-01-01'             -- user_id, status 없음
   - WHERE status = 'pending' AND created_at > '2024-01-01'  -- user_id 없음

   ⚠️ 부분 사용:
   - WHERE user_id = 1 AND created_at > '2024-01-01'
     → user_id만 인덱스 사용, created_at은 필터링

2. Range 조건 이후 컬럼은 인덱스 무효화
───────────────────────────────────────

   인덱스: (a, b, c, d)

   WHERE a = 1 AND b > 10 AND c = 'x' AND d = 'y'
         ─────     ──────     ───────────────────
         인덱스O   인덱스O    인덱스X (Range 이후)

   해결책: Range 조건 컬럼을 뒤로 배치
   인덱스: (a, c, d, b) → a, c, d 모두 인덱스 활용 후 b로 Range 스캔

3. 쓰기 성능 저하 (INSERT/UPDATE/DELETE)
────────────────────────────────────────

   ┌─────────────────────────────────────────────────────────────────┐
   │                    인덱스 개수와 쓰기 성능                       │
   ├─────────────────────────────────────────────────────────────────┤
   │                                                                 │
   │   INSERT 성능                                                   │
   │   │                                                             │
   │   │ ████████████████████████████  인덱스 0개                    │
   │   │ ██████████████████████        인덱스 1개                    │
   │   │ ████████████████              인덱스 3개                    │
   │   │ ██████████                    인덱스 5개                    │
   │   │ ██████                        인덱스 10개                   │
   │   └──────────────────────────────────────────→ 성능             │
   │                                                                 │
   │   ★ 인덱스가 많을수록 INSERT/UPDATE/DELETE 느려짐               │
   │   ★ 복합 인덱스의 컬럼 수가 많을수록 더 느려짐                   │
   │   ★ 인덱스 페이지 분할(Page Split) 발생 시 추가 오버헤드        │
   │                                                                 │
   └─────────────────────────────────────────────────────────────────┘


【 복합 인덱스 설계 Best Practices 】

1. 카디널리티(Cardinality) 고려
───────────────────────────────
   - 높은 카디널리티 컬럼을 앞에 배치 (일반적으로)
   - 하지만 쿼리 패턴이 더 중요!

   예: user_id(높음), status(낮음), created_at(높음)
   → 쿼리가 항상 user_id로 시작하면: (user_id, status, created_at)
   → 쿼리가 status로만 시작할 때도 있으면: 별도 인덱스 필요

2. 동등(=) 조건 먼저, Range 조건 나중에
───────────────────────────────────────
   WHERE user_id = 1 AND status = 'pending' AND created_at > '2024-01-01'
         ───────────────────────────────────     ────────────────────────
         동등 조건 (앞에 배치)                   Range 조건 (뒤에 배치)

3. 정렬(ORDER BY)과 그룹화(GROUP BY) 고려
────────────────────────────────────────
   -- 이 쿼리가 자주 사용된다면
   SELECT * FROM orders WHERE user_id = 1 ORDER BY created_at DESC;
   -- 인덱스: (user_id, created_at DESC)

4. 자주 사용되는 쿼리 패턴 분석
──────────────────────────────
   - EXPLAIN ANALYZE로 실행 계획 확인
   - 슬로우 쿼리 로그 분석
   - 쿼리 빈도와 중요도 고려
*/

